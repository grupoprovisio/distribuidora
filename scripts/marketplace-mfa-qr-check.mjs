import test from 'node:test';
import assert from 'node:assert/strict';
import { mfaQrImageUrl } from '../lib/marketplace/mfa-qr.ts';
const svg='<?xml version="1.0"?>\n<svg xmlns="http://www.w3.org/2000/svg"><rect width="3" height="3" /></svg>\n';
test('raw SVG and unescaped Supabase data URI become encoded URLs without control characters',()=>{
  for(const input of [svg,'data:image/svg+xml;utf-8,'+svg]){
    const url=mfaQrImageUrl(input);
    assert.ok(url.startsWith('data:image/svg+xml;charset=utf-8,%3C'));
    assert.doesNotMatch(url,/[\s<>]/);
    assert.equal(decodeURIComponent(url.split(',')[1]),svg.slice(svg.indexOf('<svg')).trim());
  }
});
test('encoded and base64 SVG data URLs remain usable',()=>{
  const url=mfaQrImageUrl(svg);assert.equal(mfaQrImageUrl(url),url);
  const base64='data:image/svg+xml;base64,'+Buffer.from(svg).toString('base64');
  assert.equal(mfaQrImageUrl(base64),base64);
});
test('arbitrary external URLs and HTML are rejected',()=>{
  for(const v of ['https://example.com/qr.png','javascript:alert(1)','<html></html>','', '<svg>', 'x'.repeat(1000001)]) assert.throws(()=>mfaQrImageUrl(v));
});

test("Auth SVG document preamble is removed before URL encoding",()=>{
 const document='<?xml version="1.0"?>\n<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" "http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">\n<svg xmlns="http://www.w3.org/2000/svg"></svg>\n';
 const url=mfaQrImageUrl("data:image/svg+xml;utf-8,"+document);
 assert.ok(url.startsWith("data:image/svg+xml;charset=utf-8,%3Csvg"));
 assert.doesNotMatch(url,/DOCTYPE/);
});

test("Supabase SVGo generated comment is accepted without retaining document preamble",()=>{
 const value='data:image/svg+xml;utf-8,<?xml version="1.0"?>\n<!-- Generated by SVGo -->\n<svg xmlns="http://www.w3.org/2000/svg"><rect /></svg>\n';
 assert.equal(decodeURIComponent(mfaQrImageUrl(value).split(",")[1]),'<svg xmlns="http://www.w3.org/2000/svg"><rect /></svg>');
});
